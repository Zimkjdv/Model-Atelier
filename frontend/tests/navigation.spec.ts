import { test, expect } from '@playwright/test'

for (const [mode, label, input] of [
  ['checkpoint', 'Checkpoint／SDXL', '#draft-prompt'], ['flux', 'FLUX.1 [schnell]', '#flux-prompt'],
  ['inpaint', '局部編輯', '#inpaint-prompt'], ['control', 'Canny 結構參考', '#control-prompt'],
]) test(`direct workflow URL and refresh: ${mode}`, async ({ page, request }) => {
  const before = (await (await request.get('/qa/state')).json()).prompts
  await page.goto('/#/studio/' + mode)
  await expect(page.locator(input)).toBeVisible()
  await expect(page.getByRole('button', { name: label, exact: true })).toHaveAttribute('aria-pressed', 'true')
  await expect(page.getByRole('navigation').getByRole('button', { name: '創作工作台' })).toHaveAttribute('aria-current', 'page')
  await expect(page.locator('main')).toBeFocused()
  await expect(page.getByLabel('提交能力狀態')).toBeVisible()
  await page.reload()
  await expect(page.locator(input)).toBeVisible()
  expect((await (await request.get('/qa/state')).json()).prompts).toBe(before)
})

test('history retains forms, focuses content, rejects malformed URL and skip link preserves route', async ({ page, request }) => {
  const before = (await (await request.get('/qa/state')).json()).prompts
  await page.goto('/#/studio/checkpoint')
  await page.locator('#draft-prompt').fill('history keeps this form')
  await page.getByRole('button', { name: 'FLUX.1 [schnell]', exact: true }).click()
  await page.locator('#flux-prompt').fill('separate flux form')
  await page.getByRole('button', { name: '參考素材', exact: true }).click()
  await page.goBack()
  await expect(page).toHaveURL(/#\/studio\/flux$/)
  await expect(page.locator('#flux-prompt')).toHaveValue('separate flux form')
  await expect(page.locator('main')).toBeFocused()
  await page.goBack()
  await expect(page.locator('#draft-prompt')).toHaveValue('history keeps this form')
  await page.goForward()
  await expect(page.locator('#flux-prompt')).toHaveValue('separate flux form')
  await page.getByRole('link', { name: '跳至主要內容' }).focus()
  await page.keyboard.press('Enter')
  await expect(page).toHaveURL(/#\/studio\/flux$/)
  await expect(page.locator('main')).toBeFocused()
  await page.evaluate(() => { location.hash = '#/studio/not-supported?generate=true' })
  await expect(page).toHaveURL(/#\/system$/)
  await expect(page.getByRole('status').filter({ hasText: '無法辨識此網址' })).toBeVisible()
  expect((await (await request.get('/qa/state')).json()).prompts).toBe(before)
})

test('back cancellation keeps unsaved artwork notes and matching URL; accepted back and forward work', async ({ page }) => {
  await page.goto('/#/system')
  await page.getByRole('button', { name: '作品庫', exact: true }).click()
  await page.getByRole('button', { name: '查看作品 qa-artwork.png', exact: true }).click()
  await page.locator('#artwork-notes').fill('history must preserve unsaved note')
  page.once('dialog', dialog => dialog.dismiss())
  await page.goBack()
  await expect(page).toHaveURL(/#\/gallery$/)
  await expect(page.locator('#artwork-notes')).toHaveValue('history must preserve unsaved note')
  page.once('dialog', dialog => dialog.accept())
  await page.goBack()
  await expect(page).toHaveURL(/#\/system$/)
  await expect(page.locator('main')).toBeFocused()
  await page.goForward()
  await expect(page).toHaveURL(/#\/gallery$/)
})

